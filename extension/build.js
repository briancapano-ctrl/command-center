// Keep each reader self-contained with its parser. No runtime code fetching or eval.
// After deploying these files, reload the unpacked add-on to activate the updated scripts.
const fs = require("fs");
const path = require("path");
const parser = fs.readFileSync(path.join(__dirname, "work_parse.js"), "utf8");
for (const name of ["work_outlook", "work_copilot"]) {
  const main = fs.readFileSync(path.join(__dirname, name + "_main.js"), "utf8");
  fs.writeFileSync(path.join(__dirname, name + ".js"), "// Generated by extension/build.js. Edit the source files, then rebuild.\n" + parser + "\n" + main);
}
